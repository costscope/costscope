// parseAnalyticsOptions parses command flags into AnalyticsOptions
func (ac *AnalyticsCommands) parseAnalyticsOptions(cmd *cobra.Command) (*types.AnalyticsOptions, error) {
	opts := &types.AnalyticsOptions{}

	// Core options
	opts.TableName, _ = cmd.Flags().GetString("table")
	opts.Currency, _ = cmd.Flags().GetString("currency")
	opts.SortOrder, _ = cmd.Flags().GetString("sort-order")

	// Parse group by fields
	groupBy, _ := cmd.Flags().GetString("group-by")
	if groupBy != "" {
		opts.GroupByFields = strings.Split(groupBy, ",")
		for i := range opts.GroupByFields {
			opts.GroupByFields[i] = strings.TrimSpace(opts.GroupByFields[i])
		}
	}

	// Parse filters JSON
	filtersJSON, _ := cmd.Flags().GetString("filters")
	if filtersJSON != "" {
		if err := json.Unmarshal([]byte(filtersJSON), &opts.Filters); err != nil {
			return nil, fmt.Errorf("invalid filters JSON: %w", err)
		}
	}

	// Parse transformations JSON
	transformationsJSON, _ := cmd.Flags().GetString("transformations")
	if transformationsJSON != "" {
		if err := json.Unmarshal([]byte(transformationsJSON), &opts.TransformationRules); err != nil {
			return nil, fmt.Errorf("invalid transformations JSON: %w", err)
		}
	}

	// Feature toggles
	opts.EnableML, _ = cmd.Flags().GetBool("enable-ml")
	opts.EnableCaching, _ = cmd.Flags().GetBool("enable-caching")
	opts.StrictTypes, _ = cmd.Flags().GetBool("strict-types")
	opts.EnableParallel, _ = cmd.Flags().GetBool("enable-parallel")

	// Performance options
	opts.MaxConcurrency, _ = cmd.Flags().GetInt("max-concurrency")
	opts.CacheTTL, _ = cmd.Flags().GetDuration("cache-ttl")

	// ML options
	opts.ForecastDays, _ = cmd.Flags().GetInt("forecast-days")
	opts.EnableAnomalyDetection = true // Default enabled
	opts.EnableTrendAnalysis = true    // Default enabled
	opts.EnablePredictions = true      // Default enabled

	return opts, nil
}

// displayResults displays analytics results in a formatted way
func (ac *AnalyticsCommands) displayResults(operation string, results *types.AnalyticsResults) error {
	fmt.Printf("\n %s Results\n", operation)
	fmt.Printf("================\n")
	fmt.Printf("Timestamp: %s\n", results.Timestamp.Format(time.RFC3339))
	fmt.Printf("Table: %s\n", results.TableName)
	fmt.Printf("Filters Applied: %d\n", results.FiltersCount)

	if len(results.AnalysisResult) > 0 {
		fmt.Printf("\n Analysis Summary:\n")
		for key, value := range results.AnalysisResult {
			fmt.Printf("  %s: %v\n", key, value)
		}
	}

	if len(results.ForecastResult) > 0 {
		fmt.Printf("\n Forecast Results:\n")
		for key, value := range results.ForecastResult {
			fmt.Printf("  %s: %v\n", key, value)
		}
	}

	if len(results.ComparisonResult) > 0 {
		fmt.Printf("\n Comparison Results:\n")
		for key, value := range results.ComparisonResult {
			fmt.Printf("  %s: %v\n", key, value)
		}
	}

	fmt.Printf("\n")
	return nil
}

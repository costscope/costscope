// AnalyticsCommands manages analytics CLI commands
type AnalyticsCommands struct {
	logger  *logging.Logger
	service analytics.Service
}

// NewAnalyticsCommands creates a new analytics commands manager
func NewAnalyticsCommands(logger *logging.Logger, service analytics.Service) *AnalyticsCommands {
	return &AnalyticsCommands{
		logger:  logger,
		service: service,
	}
}

// BuildAnalyticsCommand builds the main analytics command
// Command graph is generated by zz_generated_command_builder.go.

// runAnalyze executes the analyze command
func (ac *AnalyticsCommands) runAnalyze(cmd *cobra.Command, args []string) error {
	ac.logger.Info("Starting cost analytics analysis")

	useFocus, _ := cmd.Flags().GetBool("use-focus-engine")
	if useFocus {
		// Attempt to load optional YAML once (cached globally inside env resolver); we only need Focus section
		yamlCfg := config.LoadOptionalYAML(ac.logger)
		var flagH *int
		var flagT *time.Duration
		if v, _ := cmd.Flags().GetInt("focus-forecast-days"); v > 0 {
			flagH = &v
		}
		if v, _ := cmd.Flags().GetDuration("focus-phase-timeout"); v > 0 {
			flagT = &v
		}
		selectH := func(cc *config.ConsolidatedConfig) *int {
			if cc == nil || cc.Focus.EngineForecastDaysDefault == 0 {
				return nil
			}
			return &cc.Focus.EngineForecastDaysDefault
		}
		selectT := func(cc *config.ConsolidatedConfig) *time.Duration {
			if cc == nil || cc.Focus.EnginePhaseTimeout == 0 {
				return nil
			}
			return &cc.Focus.EnginePhaseTimeout
		}
		resolvedH := precedence.ResolveInt(flagH, selectH(yamlCfg), "COSTSCOPE_FOCUS_ENGINE_FORECAST_DAYS", 30)
		precedence.LogResolved(ac.logger, "focus.engine.forecast_days", resolvedH)
		resolvedT := precedence.ResolveDuration(flagT, selectT(yamlCfg), "COSTSCOPE_FOCUS_ENGINE_TIMEOUT", 2*time.Second)
		precedence.LogResolved(ac.logger, "focus.engine.phase_timeout", resolvedT)

		eng := focusanalysis.NewEngine(ac.logger, nil)
		dataset, _ := cmd.Flags().GetString("table")
		base, err := eng.AnalyzeFOCUSDataset(dataset, focusanalysis.AnalysisOptions{ForecastDays: resolvedH.Value, ConfidenceLevel: 0.95, OutputFormat: "json"})
		if err != nil {
			return fmt.Errorf("focus analysis failed: %w", err)
		}
		extended := focusanalysis.RunExtendedPhases(context.Background(), eng, base, resolvedH.Value, 0.95, resolvedT.Value)
		base.Extended = extended
		b, _ := json.MarshalIndent(base, "", "  ")
		fmt.Println(string(b))
		return nil
	}

	opts, err := ac.parseAnalyticsOptions(cmd)
	if err != nil {
		return fmt.Errorf("failed to parse options: %w", err)
	}
	results, err := ac.service.Analyze(opts)
	if err != nil {
		return fmt.Errorf("analysis failed: %w", err)
	}
	return ac.displayResults("Analysis", results)
}

// runForecast executes the forecast command
func (ac *AnalyticsCommands) runForecast(cmd *cobra.Command, args []string) error {
	ac.logger.Info("Starting cost forecasting")

	opts, err := ac.parseAnalyticsOptions(cmd)
	if err != nil {
		return fmt.Errorf("failed to parse options: %w", err)
	}

	// Override ML settings for forecasting
	opts.EnableML = true

	forecastDays, _ := cmd.Flags().GetInt("forecast-days")
	opts.ForecastDays = forecastDays

	results, err := ac.service.Forecast(opts)
	if err != nil {
		return fmt.Errorf("forecasting failed: %w", err)
	}

	return ac.displayResults("Forecast", results)
}


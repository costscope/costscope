func main() {
	name := flag.String("name", "", "provider name (lower-case)")
	force := flag.Bool("force", false, "overwrite existing scaffold files if safe")
	dryRun := flag.Bool("dry-run", false, "print actions only")
	flag.Parse()
	if *name == "" {
		fatal(errors.New("-name is required"))
	}
	if !regexp.MustCompile(`^[a-z0-9_]+$`).MatchString(*name) {
		fatal(fmt.Errorf("invalid provider name: %s", *name))
	}
	title := toTitle(*name)
	root, err := testutil.RepoRoot()
	if err != nil {
		fmt.Fprintf(os.Stderr, "unable to locate repo root: %v\n", err)
		os.Exit(1)
	}
	// Paths
	pDir := filepath.Join(root, "internal", "providers", *name)
	cDir := filepath.Join(root, "internal", "core", "focus", "conversion", *name)
	files := map[string]string{
		filepath.Join(pDir, "README.md"):         strings.ReplaceAll(repl(providerReadmeTemplate, *name, title), "{{TITLE}}", title),
		filepath.Join(pDir, "doc.go"):            repl(providerDocTemplate, *name, title),
		filepath.Join(pDir, "config.go"):         repl(providerConfigTemplate, *name, title),
		filepath.Join(pDir, "provider.go"):       repl(providerMainTemplate, *name, title),
		filepath.Join(pDir, "register.go"):       repl(providerRegisterTemplate, *name, title),
		filepath.Join(pDir, "provider_test.go"):  testProviderTemplate(*name),
		filepath.Join(cDir, "README.md"):         strings.ReplaceAll(repl(convReadmeTemplate, *name, title), "{{TITLE}}", title),
		filepath.Join(cDir, "headers.go"):        repl(convHeadersTemplate, *name, title),
		filepath.Join(cDir, "mapper.go"):         repl(convMapperTemplate, *name, title),
		filepath.Join(cDir, "converter.go"):      repl(convConverterTemplate, *name, title),
		filepath.Join(cDir, "converter_test.go"): repl(convTestTemplate, *name, title),
	}
	// Actions summary
	for path := range files {
		if *dryRun {
			fmt.Println("CREATE", path)
			continue
		}
		// #nosec G301 -- directories are non-sensitive scaffolds; 0750 acceptable
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			fatal(err)
		}
		if _, statErr := os.Stat(path); statErr == nil && !*force {
			fmt.Printf("SKIP (exists) %s\n", path)
			continue
		}
		if err := os.WriteFile(path, []byte(files[path]), 0o600); err != nil {
			fatal(err)
		}
		fmt.Println("WROTE", path)
	}
	if *dryRun {
		return
	}
	if err := ensureManagerImport(root, *name); err != nil {
		fatal(err)
	}
	fmt.Printf("gen-provider: scaffold complete for '%s'\n", *name)
}


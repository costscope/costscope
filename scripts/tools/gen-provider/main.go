func repl(tpl, name, title string) string {
	out := strings.ReplaceAll(tpl, "{{name}}", name)
	out = strings.ReplaceAll(out, "{{Title}}", title)
	out = strings.ReplaceAll(out, "{{TITLE}}", title)
	return out
}

func toTitle(s string) string {
	parts := strings.Split(s, "_")
	for i, p := range parts {
		if len(p) > 0 {
			parts[i] = strings.ToUpper(p[:1]) + p[1:]
		}
	}
	return strings.Join(parts, "")
}

func ensureManagerImport(root, name string) error {
	mgrPath := filepath.Join(root, "internal", "providers", "manager.go")
	// #nosec G304 -- controlled internal path, not user supplied
	b, err := os.ReadFile(mgrPath)
	if err != nil {
		return err
	}
	content := string(b)
	line := fmt.Sprintf("\t_ \"github.com/costscope/costscope/internal/providers/%s\"   // side-effect registration", name)
	if strings.Contains(content, line) {
		return nil
	}
	// Insert after last existing side-effect provider import
	lines := strings.Split(content, "\n")
	lastIdx := -1
	for i, l := range lines {
		if strings.Contains(l, "internal/providers/") && strings.Contains(l, "_ \"") {
			lastIdx = i
		}
	}
	if lastIdx == -1 {
		return errors.New("could not locate import block to patch in manager.go")
	}
	// Insert new line after lastIdx
	newLines := append([]string{}, lines[:lastIdx+1]...)
	newLines = append(newLines, line)
	newLines = append(newLines, lines[lastIdx+1:]...)
	if err := os.WriteFile(mgrPath, []byte(strings.Join(newLines, "\n")), 0o600); err != nil {
		return err
	}
	fmt.Println("UPDATED", mgrPath)
	return nil
}

